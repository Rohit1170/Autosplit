package com.example.splitwiseauto

import android.content.Context
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

@Database(
    entities = [
        Expense::class,
        Friend::class,
        ExpenseParticipant::class,
        Settlement::class,
        PendingExpenseNotification::class,
        Trip::class,
        SavedFilter::class,
        PaymentAttempt::class,
        AccountName::class,
        PendingPayment::class
    ],
    version = 13,
    // Turned on starting at v9->v10 only: this captures the schema going
    // forward (needed so the 9->10 migration test has a real v9 schema
    // JSON to build its "before" database from) without trying to
    // reconstruct schema history for versions 1-8, which nothing needs.
    // NOTE: app/schemas/9.json is generated by Room's annotation
    // processor the next time this module is compiled (kapt) — it isn't
    // produced by this edit alone, so a build must run once locally
    // before AppDatabaseMigrationTest can find it.
    exportSchema = true
)
abstract class AppDatabase : RoomDatabase() {

    abstract fun expenseDao(): ExpenseDao

    abstract fun friendDao(): FriendDao

    abstract fun expenseParticipantDao(): ExpenseParticipantDao

    abstract fun settlementDao(): SettlementDao

    abstract fun pendingExpenseNotificationDao(): PendingExpenseNotificationDao

    abstract fun tripDao(): TripDao

    abstract fun savedFilterDao(): SavedFilterDao

    abstract fun paymentAttemptDao(): PaymentAttemptDao

    abstract fun pendingPaymentDao(): PendingPaymentDao

    companion object {

        private val MIGRATION_1_2 = object : Migration(1, 2) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL("ALTER TABLE expenses ADD COLUMN latitude REAL")
                database.execSQL("ALTER TABLE expenses ADD COLUMN longitude REAL")
            }
        }

        private val MIGRATION_2_3 = object : Migration(2, 3) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL(
                    "ALTER TABLE expenses ADD COLUMN category TEXT NOT NULL DEFAULT 'Other'"
                )
            }
        }

        private val MIGRATION_3_4 = object : Migration(3, 4) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL("ALTER TABLE expenses ADD COLUMN accountIdentifier TEXT")
            }
        }

        private val MIGRATION_4_5 = object : Migration(4, 5) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL(
                    "CREATE TABLE IF NOT EXISTS `settlements` (" +
                        "`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, " +
                        "`friendId` INTEGER NOT NULL, " +
                        "`amount` REAL NOT NULL, " +
                        "`settledAt` INTEGER NOT NULL)"
                )
            }
        }

        // Best-effort parse of the free-form `date` strings already in the
        // table, so existing rows still show up in month-based views. Anything
        // that doesn't match a known bank/date format is left null rather than
        // guessed at.
        private val LEGACY_DATE_FORMATS = listOf(
            "dd-MMM-yy", "dd-MMM-yyyy", "dd MMM yyyy", "dd MMM yy",
            "dd-MM-yyyy", "dd/MM/yyyy", "dd-MM-yy", "dd/MM/yy"
        ).map { java.text.SimpleDateFormat(it, java.util.Locale.US).apply { isLenient = false } }

        private fun parseLegacyDateToMillis(rawDate: String?): Long? {
            val trimmed = rawDate?.trim().orEmpty()
            if (trimmed.isEmpty() || trimmed.equals("Unknown", ignoreCase = true)) return null
            for (format in LEGACY_DATE_FORMATS) {
                runCatching { format.parse(trimmed)?.time }.getOrNull()?.let { return it }
            }
            return null
        }

        private val MIGRATION_5_6 = object : Migration(5, 6) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL("ALTER TABLE expenses ADD COLUMN timestampMillis INTEGER")

                val cursor = database.query("SELECT id, date FROM expenses")
                cursor.use {
                    val idIndex = it.getColumnIndexOrThrow("id")
                    val dateIndex = it.getColumnIndexOrThrow("date")
                    while (it.moveToNext()) {
                        val id = it.getInt(idIndex)
                        val rawDate = it.getString(dateIndex)
                        val millis = parseLegacyDateToMillis(rawDate) ?: continue
                        database.execSQL(
                            "UPDATE expenses SET timestampMillis = ? WHERE id = ?",
                            arrayOf(millis, id)
                        )
                    }
                }
            }
        }

        private val MIGRATION_6_7 = object : Migration(6, 7) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL(
                    "CREATE TABLE IF NOT EXISTS `pending_expense_notifications` (" +
                        "`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, " +
                        "`amount` TEXT NOT NULL, " +
                        "`merchant` TEXT NOT NULL, " +
                        "`bank` TEXT NOT NULL, " +
                        "`date` TEXT NOT NULL, " +
                        "`balance` TEXT NOT NULL, " +
                        "`upi` TEXT NOT NULL, " +
                        "`accountIdentifier` TEXT, " +
                        "`latitude` REAL, " +
                        "`longitude` REAL, " +
                        "`timestampMillis` INTEGER NOT NULL, " +
                        "`createdAtMillis` INTEGER NOT NULL)"
                )
            }
        }

        // Purely additive: a new "trips" table plus a new nullable column on
        // the existing expenses table. No data is dropped, moved, or
        // recreated, so every expense you've already recorded stays exactly
        // as it is.
        private val MIGRATION_7_8 = object : Migration(7, 8) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL(
                    "CREATE TABLE IF NOT EXISTS `trips` (" +
                        "`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, " +
                        "`name` TEXT NOT NULL, " +
                        "`createdAtMillis` INTEGER NOT NULL)"
                )
                database.execSQL("ALTER TABLE expenses ADD COLUMN tripId INTEGER")
            }
        }

        // Purely additive: one new table for saved custom filters. Nothing
        // about expenses, friends, or any other existing data changes.
        private val MIGRATION_8_9 = object : Migration(8, 9) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL(
                    "CREATE TABLE IF NOT EXISTS `saved_filters` (" +
                        "`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, " +
                        "`name` TEXT NOT NULL, " +
                        "`startMillis` INTEGER NOT NULL, " +
                        "`endMillis` INTEGER NOT NULL, " +
                        "`createdAtMillis` INTEGER NOT NULL)"
                )
            }
        }

        // Purely additive: one new table for Scan & Pay's payment attempts,
        // plus one nullable column each on the two existing tables it links
        // to (pending_expense_notifications for the queue badge, expenses
        // for the audit link once a payment is confirmed and split). No
        // existing column is altered, dropped, or renamed, and no existing
        // row is rewritten — every expense and pending notification already
        // recorded keeps every value it has.
        // Not private: AppDatabaseMigrationTest (androidTest) references
        // this directly with Room's MigrationTestHelper.
        val MIGRATION_9_10 = object : Migration(9, 10) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL(
                    "CREATE TABLE IF NOT EXISTS `payment_attempts` (" +
                        "`id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, " +
                        "`upiId` TEXT NOT NULL, " +
                        "`payeeName` TEXT, " +
                        "`expectedAmount` REAL NOT NULL, " +
                        "`status` TEXT NOT NULL, " +
                        "`createdAtMillis` INTEGER NOT NULL, " +
                        "`simSlot` INTEGER, " +
                        "`rail` TEXT NOT NULL, " +
                        "`adoptedExpenseId` INTEGER)"
                )
                database.execSQL(
                    "ALTER TABLE pending_expense_notifications ADD COLUMN source TEXT"
                )
                database.execSQL(
                    "ALTER TABLE pending_expense_notifications ADD COLUMN paymentAttemptId INTEGER"
                )
                database.execSQL(
                    "ALTER TABLE expenses ADD COLUMN paymentAttemptId INTEGER"
                )
            }
        }

        // Purely additive: one new table (now backed by the AccountName
        // entity), matching exactly what a prior build already created
        // on-device (app/schemas/.../11.json). Needed on both counts —
        // this migration creates the table for anyone still on v10, and
        // declaring AccountName as a real entity is what makes Room's
        // schema-identity check pass on devices that already have it. No
        // existing table, column, or row is touched, so every expense,
        // friend, and everything else already recorded stays exactly as
        // it is.
        val MIGRATION_10_11 = object : Migration(10, 11) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL(
                    "CREATE TABLE IF NOT EXISTS `account_names` (" +
                        "`idKey` TEXT NOT NULL, " +
                        "`displayName` TEXT NOT NULL, " +
                        "PRIMARY KEY(`idKey`))"
                )
            }
        }

        // Purely additive: one new table for UPI-intent Scan & Pay payments
        // (PendingPayment). No existing table, column, or row is touched —
        // payment_attempts from the old *99# flow is left exactly as it is.
        // Column types/nullability must match PendingPayment exactly for
        // Room's schema validation.
        val MIGRATION_11_12 = object : Migration(11, 12) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL(
                    "CREATE TABLE IF NOT EXISTS `pending_payments` (" +
                        "`id` TEXT NOT NULL, " +
                        "`billId` TEXT, " +
                        "`amountMinor` INTEGER NOT NULL, " +
                        "`payeeVpa` TEXT NOT NULL, " +
                        "`payeeName` TEXT, " +
                        "`initiatedAt` INTEGER NOT NULL, " +
                        "`status` TEXT NOT NULL, " +
                        "`upiRef` TEXT, " +
                        "`confirmedAt` INTEGER, " +
                        "PRIMARY KEY(`id`))"
                )
            }
        }

        // Purely additive: no table, column, or row is touched — these just
        // add SQLite indices on top of what's already there, so lookups by
        // trip, date, expense, or person stop being full table scans as
        // your expense history grows. Every expense, friend, and everything
        // else already recorded stays exactly as it is.
        val MIGRATION_12_13 = object : Migration(12, 13) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL(
                    "CREATE INDEX IF NOT EXISTS `index_expenses_tripId` ON `expenses` (`tripId`)"
                )
                database.execSQL(
                    "CREATE INDEX IF NOT EXISTS `index_expenses_timestampMillis` ON `expenses` (`timestampMillis`)"
                )
                database.execSQL(
                    "CREATE INDEX IF NOT EXISTS `index_expense_participants_expenseId` ON `expense_participants` (`expenseId`)"
                )
                database.execSQL(
                    "CREATE INDEX IF NOT EXISTS `index_expense_participants_personName` ON `expense_participants` (`personName`)"
                )
            }
        }

        @Volatile
        private var INSTANCE: AppDatabase? = null

        fun getDatabase(
            context: Context
        ): AppDatabase {

            return INSTANCE ?: synchronized(this) {

                val instance = Room.databaseBuilder(
                    context.applicationContext,
                    AppDatabase::class.java,
                    "splitwise_auto_database"
                )
                    .addMigrations(
                        MIGRATION_1_2,
                        MIGRATION_2_3,
                        MIGRATION_3_4,
                        MIGRATION_4_5,
                        MIGRATION_5_6,
                        MIGRATION_6_7,
                        MIGRATION_7_8,
                        MIGRATION_8_9,
                        MIGRATION_9_10,
                        MIGRATION_10_11,
                        MIGRATION_11_12,
                        MIGRATION_12_13
                    )
                    .build()

                INSTANCE = instance

                instance
            }
        }
    }
}
